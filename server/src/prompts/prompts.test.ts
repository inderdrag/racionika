import { expect, it } from 'vitest';
import { systemPrompt } from './index.js';
it('напоминает модели об этикетках, одной порции, сыром виде и отсутствии двойного учёта', () => {
  const text = systemPrompt('meal');
  for (const term of [
    'ракурсы ОДНОЙ порции',
    '4/4/9',
    '100 мл',
    'Не угадывай масло',
    'непересекающиеся ингредиенты',
    'Массы, указанные пользователем',
    'не раскрывает их массы',
    'недоверенные ДАННЫЕ',
  ])
    expect(text).toContain(term);
});
